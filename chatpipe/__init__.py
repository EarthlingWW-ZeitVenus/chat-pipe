# -*- coding: utf-8 -*-
"""
chatpipe - конвейер, который превращает историю чатов с ИИ в сухие служебные документы.

------------------------------------------------------------------------------
ЧТО ТАКОЕ ЭТОТ ФАЙЛ
------------------------------------------------------------------------------
Файл с именем __init__.py превращает обычную папку в "пакет" Python: после этого
из неё можно импортировать модули (from chatpipe.schema import ...). Код из этого
файла выполняется один раз, когда пакет подключают. Здесь мы держим только то,
что нужно всем модулям сразу: префикс имён файлов и версию программы.

------------------------------------------------------------------------------
КАРТА ПАКЕТА: КТО ЗА ЧТО ОТВЕЧАЕТ
------------------------------------------------------------------------------
  names.py                   все имена файлов программы в одном месте.
  schema.py                  ДОГОВОР между стадиями: как выглядит "карточка"
                             (один обмен "запрос - ответ"), проверка карточек,
                             чтение и запись файлов .jsonl.
  settings.py                паспорт запуска: файл пользовательских настроек
                             с комментариями к каждому полю.
  text_tools.py              общие текстовые инструменты (HTML -> Markdown, хэш,
                             деление Markdown на текст и код).
  redaction.py               маскирование секретов (пароли, ключи, токены).

  ЭТАП 1 (файл экспорта -> карточки):
  adapters/                  "переводчики" из конкретных форматов экспорта в
                             стандартные карточки:
      __init__.py              реестр профилей источников
      gemini_takeout_html.py   Gemini через Google Takeout (HTML)
  stage1_report.py           отчёт и файл версий служебного блока.
  stage1_ingest.py           "пульт" этапа 1 (запуск: run_stage1.py).

  ЭТАП 2 (карточки -> метки -> пачки для ИИ; читает карточки только через schema.py):
  dictionary.py              словарь понятий: слова-синонимы, идентификаторы, уровни.
  annotations.py             слой аннотаций: статусы карточек и метки (хранятся отдельно).
  keywords.py                значимые слова карточек (BM25), леммы, выборка предложений.
  rules.py                   правила меток: логические выражения над словами.
  xml_render.py              сборка XML для ИИ (текст и код в CDATA).
  bundles.py                 группировка готовых карточек по темам и нарезка на пачки.
  console.py                 текстовый ввод-вывод (вопросы, меню, постраничный показ).
  stage2_session.py          ядро этапа 2: данные сеанса и действия над ними.
  stage2_menus.py            терминальные меню этапа 2.
  stage2_label.py            точка входа этапа 2 (запуск: run_stage2.py).

------------------------------------------------------------------------------
ГЛАВНЫЙ ПРИНЦИП
------------------------------------------------------------------------------
Каждый модуль делает одно дело и знает о соседях как можно меньше.
Стадия 2 и дальше импортируют ТОЛЬКО schema.py: они ничего не знают о Takeout,
Claude или DeepSeek. Новый источник = один новый файл-адаптер в папке adapters/
плюс одна строка в реестре.
"""

# Префикс имён файлов данных: [префикс]_[смысл]_[стадия].[расширение].
# Если захотите переименовать программу, достаточно поменять эту строку - все
# модули берут префикс отсюда, а не пишут его в каждом имени вручную.
PREFIX = "chatpipe"

# Версия программы. Версия живёт ВНУТРИ кода (а не в именах файлов), поэтому
# файлы не нужно переименовывать при каждом обновлении.
__version__ = "0.1.0"
