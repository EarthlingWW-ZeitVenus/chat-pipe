# -*- coding: utf-8 -*-
"""
schema.py - ДОГОВОР между стадиями конвейера.

Это единственный модуль, который должны импортировать стадии 2, 3 и далее.
Они ничего не знают о Takeout, Claude или DeepSeek: они читают стандартные
"карточки" через read_cards() и больше ни о чём не заботятся.

------------------------------------------------------------------------------
ЧТО ТАКОЕ КАРТОЧКА
------------------------------------------------------------------------------
Одна карточка = один обмен "запрос пользователя - ответ ИИ".
В памяти программы карточка - это словарь (dict), в файле - одна строка JSON.

  Поле                Тип      Может быть null   Что это
  ------------------  -------  ----------------  --------------------------------
  schema_version      число    нет               версия договора (сейчас 1)
  id                  текст    нет               стабильный идентификатор
  source              текст    нет               профиль источника, напр. gemini-takeout-html
  conversation_id     текст    ДА                идентификатор чата (если источник его даёт)
  conversation_title  текст    ДА                название чата (если источник его даёт)
  ts                  текст    ДА                время в формате ISO 8601 С часовым поясом
  prompt              текст    нет               запрос пользователя, чистый текст
  answer_md           текст    нет               ответ ИИ в Markdown
  service_md          текст    ДА                встроенный "служебный файл", если он есть
  meta                словарь  нет               всё прочее, специфичное для источника

------------------------------------------------------------------------------
ПРАВИЛА ФАЙЛА .jsonl
------------------------------------------------------------------------------
  * кодировка UTF-8, одна карточка на строку;
  * карточки идут в хронологическом порядке (по ts, от старых к новым);
    карточки без времени (ts = null) стоят в самом конце;
  * поле id уникально внутри файла;
  * секреты уже замаскированы (это делает пульт стадии 1, см. redaction.py).

------------------------------------------------------------------------------
ЗАЧЕМ ПРОВЕРКА (validate_card)
------------------------------------------------------------------------------
Договор работает, только если его кто-то проверяет. Проверка стоит на "границе":
при записи (write_cards) и при чтении (read_cards). Если в новом адаптере ошибка,
мы получим сразу понятное сообщение ("карточка №17: нет поля prompt"), а не
странный сбой через три стадии или тихо неверный результат.
"""

import json                       # чтение и запись JSON
import os                         # os.replace - атомарная замена файла
from datetime import datetime, timezone  # работа с датой и временем
from pathlib import Path          # удобная работа с путями к файлам


# ==============================================================================
# ОПИСАНИЕ ДОГОВОРА
# ==============================================================================

# Текущая версия договора и список версий, которые умеет читать этот код.
# Когда договор изменится (новые поля и т.п.), версия станет 2, а старые файлы
# можно будет прочитать по номеру версии, а не гадать.
SCHEMA_VERSION = 1
SUPPORTED_VERSIONS = (1,)

# Таблица полей: (имя, ожидаемый_тип, может_ли_быть_null).
# Это и есть "договор" в виде данных. Проверка ниже просто идёт по этой таблице,
# поэтому при изменении договора правится одно место.
FIELD_SPECS = [
    ("schema_version", int, False),
    ("id", str, False),
    ("source", str, False),
    ("conversation_id", str, True),
    ("conversation_title", str, True),
    ("ts", str, True),
    ("prompt", str, False),
    ("answer_md", str, False),
    ("service_md", str, True),
    ("meta", dict, False),
]


class CardValidationError(ValueError):
    """Ошибка: карточка или файл карточек не соответствуют договору.

    Мы создаём СВОЙ тип ошибки (на основе встроенного ValueError), чтобы вызывающий
    код мог отличать именно нарушения договора от любых других ошибок:
        try: ...  except CardValidationError: ...
    Тело класса пустое (pass не нужен, достаточно строки документации): всё
    поведение берётся от ValueError.
    """


# ==============================================================================
# ВРЕМЯ
# ==============================================================================

def ts_to_datetime(ts):
    """Превращает текст времени ISO 8601 из карточки в объект datetime.

    Вход:  ts - строка вида "2026-07-13T14:41:33+03:00" или None.
    Выход: объект datetime (с часовым поясом) или None, если ts равно None.
    Бросает ValueError, если строка не похожа на дату.
    """
    if ts is None:
        return None
    return datetime.fromisoformat(ts)


# "Нулевая точка" времени. Нужна как запасное значение при сортировке, когда у
# карточки нет времени (см. card_sort_key). timezone.utc - часовой пояс UTC;
# datetime с поясом можно сравнивать только с другим datetime с поясом.
_EPOCH = datetime(1970, 1, 1, tzinfo=timezone.utc)


def card_sort_key(card):
    """Ключ сортировки карточек: сначала карточки со временем (по возрастанию), потом без времени.

    Как это работает: sort() и sorted() умеют сравнивать пары (кортежи).
    Кортеж сравнивается по первому элементу, при равенстве - по второму.
      * Первый элемент (dt is None) равен False для карточек со временем и True
        для карточек без времени. Поскольку False < True, карточки без времени
        уходят в конец.
      * Второй элемент - само время (для карточек без времени подставляем _EPOCH,
        чтобы сравнение не сломалось на None).
    Использование:  cards.sort(key=card_sort_key)
    """
    dt = ts_to_datetime(card.get("ts"))
    return (dt is None, dt if dt is not None else _EPOCH)


# ==============================================================================
# ПРОВЕРКА КАРТОЧКИ
# ==============================================================================

def validate_card(card):
    """Проверяет ОДНУ карточку на соответствие договору.

    Вход:  card - то, что хотим проверить (должно быть словарём).
    Выход: список текстовых описаний проблем. ПУСТОЙ список = карточка в порядке.

    Почему функция возвращает список, а не бросает ошибку: так можно показать
    сразу ВСЕ проблемы карточки, а не только первую, и функцию легко тестировать.
    """
    # Если пришёл не словарь, дальше проверять нечего.
    if not isinstance(card, dict):
        return [f"карточка должна быть словарём, а не {type(card).__name__}"]

    problems = []

    # --- Проход по таблице полей.
    for name, expected_type, nullable in FIELD_SPECS:
        if name not in card:
            problems.append(f"нет обязательного поля '{name}'")
            continue  # к следующему полю: проверять тип отсутствующего значения нельзя

        value = card[name]

        if value is None:
            if not nullable:
                problems.append(f"поле '{name}' не может быть null")
            continue

        # Особенность Python: bool (True/False) - это подвид int (True == 1).
        # Чтобы "true" не сошло за число, отдельно отсекаем bool.
        # isinstance(значение, тип) отвечает на вопрос "это значение такого типа?".
        if isinstance(value, bool) or not isinstance(value, expected_type):
            problems.append(
                f"поле '{name}' должно быть типа {expected_type.__name__}, "
                f"а не {type(value).__name__}")

    # --- Проверки смысла (а не только типов). Делаем их, только если тип верный,
    # иначе получим лишние ошибки-"эхо" от уже найденной проблемы.
    version = card.get("schema_version")
    if isinstance(version, int) and not isinstance(version, bool):
        if version not in SUPPORTED_VERSIONS:
            problems.append(
                f"версия договора {version} не поддерживается "
                f"(поддерживаются: {list(SUPPORTED_VERSIONS)})")

    if card.get("id") == "":
        problems.append("поле 'id' не может быть пустой строкой")

    if card.get("source") == "":
        problems.append("поле 'source' не может быть пустой строкой")

    ts = card.get("ts")
    if isinstance(ts, str):
        try:
            dt = ts_to_datetime(ts)
        except ValueError:
            problems.append(f"поле 'ts' ({ts!r}) не похоже на дату ISO 8601")
        else:
            # try/except/else: блок else выполняется, только если ошибки НЕ было.
            # Время без часового пояса сравнивать с другим временем нельзя
            # (Python бросит ошибку), поэтому договор требует пояс.
            if dt.tzinfo is None:
                problems.append("поле 'ts' должно содержать часовой пояс (например +03:00)")

    return problems


