def _describe(card, number):
    """Короткое описание карточки для сообщений об ошибках: "карточка №17 (id=..., source=...)"."""
    cid = card.get("id") if isinstance(card, dict) else None
    src = card.get("source") if isinstance(card, dict) else None
    return f"карточка №{number} (id={cid!r}, source={src!r}): "


def _check_in_sequence(card, number, state):
    """Проверяет карточку И её место в файле: порядок по времени и уникальность id.

    state - словарь, который переходит от карточки к карточке и хранит память о
    предыдущих: {"prev_key": ключ_сортировки_предыдущей, "ids": множество_уже_виденных_id}.
    Бросает CardValidationError при любом нарушении.
    """
    # 1) Сама карточка.
    problems = validate_card(card)
    if problems:
        raise CardValidationError(_describe(card, number) + "; ".join(problems))

    # 2) Хронологический порядок: ключ текущей не должен быть меньше предыдущей.
    key = card_sort_key(card)
    if state["prev_key"] is not None and key < state["prev_key"]:
        raise CardValidationError(
            _describe(card, number) + "нарушен хронологический порядок "
            "(карточка раньше предыдущей по времени)")
    state["prev_key"] = key

    # 3) Уникальность id. Множество (set) хранит каждое значение один раз и
    # умеет мгновенно отвечать "это значение уже есть?".
    if card["id"] in state["ids"]:
        raise CardValidationError(_describe(card, number) + "повторяющийся id")
    state["ids"].add(card["id"])


def write_cards(path, cards):
    """Записывает карточки в файл .jsonl, проверяя договор по ходу дела.

    Вход:  path - куда писать; cards - любой набор карточек, который можно перебрать
           циклом (список, генератор...).
    Выход: сколько карточек записано.

    Запись "атомарная": сначала всё пишется во временный файл, и только если
    ошибок не было, он переименовывается в настоящий. Так при ошибке (или Ctrl+C)
    на диске не останется наполовину записанного файла, а старая версия цела.
    """
    path = Path(path)
    tmp_path = path.with_name(path.name + ".tmp")  # например cards.jsonl.tmp
    state = {"prev_key": None, "ids": set()}
    count = 0

    try:
        with tmp_path.open("w", encoding="utf-8") as f:
            for number, card in enumerate(cards, 1):
                _check_in_sequence(card, number, state)
                # ensure_ascii=False оставляет кириллицу читаемой (иначе она была бы
                # записана кодами \u043f...). "\n" - конец строки: одна карточка на строку.
                f.write(json.dumps(card, ensure_ascii=False) + "\n")
                count = number
        os.replace(tmp_path, path)  # атомарная замена: файл либо старый, либо новый целиком
    except BaseException:
        # BaseException ловит вообще любую ошибку, включая прерывание Ctrl+C.
        # Убираем недописанный временный файл и пробрасываем ошибку дальше (raise).
        if tmp_path.exists():
            tmp_path.unlink()  # unlink - удалить файл
        raise
    return count


def read_cards(path, check_order=True):
    """Читает карточки из файла .jsonl и по одной отдаёт вызывающему коду.

    Это ГЕНЕРАТОР: функция с yield. Она не читает весь файл сразу, а отдаёт
    карточки по одной, по мере запроса (for card in read_cards(path): ...).
    Поэтому файл любого размера читается без нагрузки на память.

    Каждая карточка проверяется на соответствие договору; при нарушении
    бросается CardValidationError с номером карточки.
    check_order=False отключает проверку порядка и уникальности id (нужно
    только для разбора заведомо "сырых" файлов).
    """
    state = {"prev_key": None, "ids": set()}
    with Path(path).open("r", encoding="utf-8") as f:
        for number, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue  # пустые строки пропускаем
            try:
                card = json.loads(line)
            except json.JSONDecodeError as e:
                # "from e" сохраняет исходную ошибку в цепочке, чтобы при отладке
                # было видно, что именно сломалось внутри json.
                raise CardValidationError(
                    f"{path}, строка {number}: это не корректный JSON ({e})") from e

            if check_order:
                _check_in_sequence(card, number, state)
            else:
                problems = validate_card(card)
                if problems:
                    raise CardValidationError(_describe(card, number) + "; ".join(problems))
            yield card
