# -*- coding: utf-8 -*-
"""
redaction.py - маскирование секретов в тексте.

В чатах попадаются пароли и ключи. Дальше этот текст пойдёт к моделям ИИ и в
служебные файлы, поэтому секреты заменяем на метки вида <REDACTED:тип>.

Что здесь есть:
  redact(text, counter)        замаскировать секреты в одном тексте
  redact_card(card, counter)   замаскировать секреты во всех текстовых полях карточки

ВАЖНО: это эвристики (поиск по шаблонам). Они страхуют, но не заменяют смену
ключей, которые уже побывали в облачных чатах.

Почему это отдельный модуль: маскировка нужна ЛЮБОМУ источнику (Takeout, Claude,
DeepSeek), поэтому её вызывает общий "пульт" (stage1_ingest.py) после адаптера, а
не каждый адаптер по отдельности. Так её нельзя забыть при добавлении нового
источника.
"""

import re  # регулярные выражения: язык шаблонов для поиска и замены текста


# ==============================================================================
# ШАБЛОНЫ СЕКРЕТОВ
# ==============================================================================
# Каждый элемент списка - тройка: (название, шаблон, номер_группы).
#   * номер_группы = None: найденное заменяется целиком.
#   * номер_группы = 2: группа 1 (имя переменной и знак "=") сохраняется, а
#     группа 2 (само значение) заменяется. Так в тексте остаётся понятно, ЧТО
#     это за переменная, но не её значение.
#
# Пояснения к самым сложным шаблонам (внутрь самих шаблонов комментарии не
# вставить - там важен каждый символ):
#
# "env_secret" ловит строки вида   DB_PASSWORD=значение   (формат .env):
#   (?im)   флаги: i - не различать регистр букв; m - ^ означает начало
#           КАЖДОЙ строки, а не только всего текста
#   ^       начало строки
#   ( ... ) группа 1 - то, что сохраняем:
#     [ \t>\d]*              допускаем в начале пробелы, табы, ">" и цифры
#                            (так выглядят строки, скопированные из редактора
#                            с нумерацией: " 1 DB_PASSWORD=...")
#     (?:export[ \t]+)?      необязательное слово export
#     [A-Za-z0-9_.\-]*       начало имени переменной
#     (?:PASSWORD|PASSWD|PASS|SECRET|TOKEN|API_?KEY|ACCESS_?KEY|PRIVATE_?KEY|KEY)
#                            в имени должно быть одно из "секретных" слов
#     [A-Za-z0-9_.\-]*       конец имени
#     [ \t]*=[ \t]*["']?     знак "=" и возможная открывающая кавычка
#   (?![\$<{])               "негативная проверка вперёд": значение НЕ должно
#                            начинаться с $, < или { - это ссылки на переменные
#                            (${DB_PASSWORD}) или заглушки (<пароль>), а не
#                            настоящие секреты
#   ([^\s"']{4,})            группа 2 - само значение: 4+ символов без пробелов
#                            и кавычек. Оно и заменяется.
#
# "yaml_secret" - то же для формата YAML (password: значение), только с двоеточием
#   и без слова KEY (иначе слишком много ложных срабатываний на обычном тексте).
#
# Остальные шаблоны ищут ключи с характерным видом: sk-... (OpenAI/OpenRouter),
# sk_live_... (Stripe), ghp_... (GitHub), AKIA... (AWS), AIza... (Google) и т.д.
#
# "url_credentials": (?<=://) - "позади должно стоять ://" ("позитивная проверка
#   назад"); дальше "логин:пароль", а (?=@) - "впереди должна стоять @".
#   Ловит postgresql://user:password@host, при этом заменяет только "user:password".
SECRET_PATTERNS = [
    ("private_key_block", re.compile(
        r"-----BEGIN [A-Z ]*PRIVATE KEY-----.*?-----END [A-Z ]*PRIVATE KEY-----", re.S), None),
    ("env_secret", re.compile(
        r"(?im)^([ \t>\d]*(?:export[ \t]+)?[A-Za-z0-9_.\-]*"
        r"(?:PASSWORD|PASSWD|PASS|SECRET|TOKEN|API_?KEY|ACCESS_?KEY|PRIVATE_?KEY|KEY)"
        r"[A-Za-z0-9_.\-]*[ \t]*=[ \t]*[\"']?)(?![\$<{])([^\s\"']{4,})"), 2),
    ("yaml_secret", re.compile(
        r"(?im)^([ \t\-]*(?:password|passwd|secret|token|api[_-]?key)[ \t]*:[ \t]*[\"']?)"
        r"(?![\$<{])([^\s\"']{4,})"), 2),
    ("openai_like_key", re.compile(r"\bsk-[A-Za-z0-9_\-]{16,}"), None),
    ("stripe_key", re.compile(r"\b[rs]k_(?:live|test)_[A-Za-z0-9]{10,}"), None),
    ("github_token", re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}"), None),
    ("aws_key_id", re.compile(r"\bAKIA[0-9A-Z]{16}\b"), None),
    ("google_api_key", re.compile(r"\bAIza[0-9A-Za-z_\-]{30,}"), None),
    ("bearer_token", re.compile(r"(?i)\bBearer[ \t]+[A-Za-z0-9._\-]{20,}"), None),
    ("url_credentials", re.compile(r"(?<=://)[^/\s:@]+:[^/\s@]+(?=@)"), None),
]

# Текстовые поля карточки, в которых ищем секреты. Названия полей - из договора
# (schema.py). Числовые поля и "meta" не трогаем: там секретов быть не должно.
TEXT_FIELDS = ("prompt", "answer_md", "service_md", "conversation_title")


def redact(text, counter):
    """Маскирует секреты в тексте и считает, сколько и каких нашлось.

    Вход:  text - исходный текст; counter - Counter, куда добавляем счётчики.
    Выход: текст с замаскированными секретами. Сами значения секретов нигде не
           сохраняются: в counter попадают только названия типов и количества.
    """
    # Проходим по всем шаблонам по очереди. Порядок важен: сначала целые
    # приватные ключи, потом остальное.
    # "for name, rx, group in ..." распаковывает каждую тройку в три переменные.
    for name, rx, group in SECRET_PATTERNS:
        if group is None:
            # rx.subn(замена, текст) делает замену и возвращает ПАРУ:
            # (новый_текст, сколько_замен).
            text, n = rx.subn(f"<REDACTED:{name}>", text)
        else:
            # Когда нужно сохранить часть найденного (имя переменной), вместо
            # готовой строки передаём ФУНКЦИЮ. lambda - короткая безымянная
            # функция: "для найденного m верни группу 1 + метку".
            # Запись "name=name" - важный приём: она "фиксирует" текущее значение
            # name внутри lambda. Без неё все lambda ссылались бы на переменную
            # цикла и использовали её последнее значение (известная ловушка Python).
            text, n = rx.subn(lambda m, name=name: m.group(1) + f"<REDACTED:{name}>", text)
        if n:
            counter[name] += n  # увеличиваем счётчик этого типа на число замен
    return text


def redact_card(card, counter):
    """Маскирует секреты во всех текстовых полях карточки.

    Карточка - словарь (см. schema.py). Функция ИЗМЕНЯЕТ его на месте и заодно
    возвращает его же: так удобно писать и "redact_card(card, c)" отдельной
    строкой, и "cards.append(redact_card(card, c))".
    """
    for field in TEXT_FIELDS:
        value = card.get(field)  # .get вернёт None, если поля нет
        if value:                # None и пустую строку пропускаем: маскировать нечего
            card[field] = redact(value, counter)
    return card
