def _render(entries, values, indent):
    """Превращает шаблон и значения в список строк файла (с комментариями).

    Вход:  entries - записи шаблона; values - словарь значений для этого уровня;
           indent - уровень вложенности (для отступов).
    Выход: список строк.
    Функция вызывает сама себя для вложенных разделов - это называется рекурсией.
    """
    lines = []
    pad = "  " * indent  # отступ: 2 пробела на уровень
    for i, entry in enumerate(entries):
        # Запятая нужна после каждого элемента, кроме последнего (так требует JSON).
        is_last = (i == len(entries) - 1)
        comma = "" if is_last else ","

        if entry[0] == "leaf":
            _, key, default, comment = entry
            value = values.get(key, default)
            # Комментарий к полю - строки "// ..." прямо над ним.
            lines += [f"{pad}// {c}" for c in comment]
            # json.dumps превращает значение Python в текст JSON:
            #   None -> null, False -> false, "текст" -> "текст".
            lines.append(f"{pad}{json.dumps(key)}: {json.dumps(value, ensure_ascii=False)}{comma}")
        else:
            _, key, comment, children = entry
            sub_values = values.get(key, {})
            if not isinstance(sub_values, dict):
                sub_values = {}
            lines += [f"{pad}// {c}" for c in comment]
            lines.append(f"{pad}{json.dumps(key)}: {{")  # "{{" в f-строке даёт одну "{"
            lines += _render(children, sub_values, indent + 1)
            lines.append(f"{pad}}}{comma}")              # "}}" в f-строке даёт одну "}"

        if not is_last:
            lines.append("")  # пустая строка между полями для читаемости
    return lines


def render_settings(values=None):
    """Возвращает полный текст файла настроек (шапка + поля с комментариями)."""
    merged = _merge(default_settings(), values or {})
    body = _render(TEMPLATE, merged, 1)
    return "\n".join(HEADER_LINES + ["", "{"] + body + ["}"]) + "\n"


def save_settings(path, values=None):
    """Сохраняет настройки в файл. Недостающие поля берутся по умолчанию.

    Запись атомарная (сначала временный файл, потом замена), как в schema.write_cards:
    при сбое старый файл настроек остаётся целым.
    """
    path = Path(path)
    tmp_path = path.with_name(path.name + ".tmp")
    tmp_path.write_text(render_settings(values), encoding="utf-8")
    os.replace(tmp_path, path)


