def main(argv=None):
    """Создаёт файл настроек по умолчанию (чтобы его можно было открыть и посмотреть)."""
    ap = argparse.ArgumentParser(description="Создать файл настроек chatpipe по умолчанию")
    # nargs="?" - аргумент необязателен; если не указан, берётся default.
    ap.add_argument("path", nargs="?", default=SETTINGS_FILE_DEFAULT,
                    help=f"куда записать файл (по умолчанию {SETTINGS_FILE_DEFAULT})")
    # action="store_true": флаг без значения; есть в команде - True, нет - False.
    ap.add_argument("--force", action="store_true", help="перезаписать, если файл уже есть")
    args = ap.parse_args(argv)

    target = Path(args.path)
    if target.exists() and not args.force:
        # Защита от случайной потери ваших настроек.
        print(f"Файл уже существует: {target}. Для перезаписи добавьте --force", file=sys.stderr)
        return 1
    save_settings(target)
    print(f"Создан файл настроек: {target.resolve()}")
    return 0


