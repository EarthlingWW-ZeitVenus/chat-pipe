def _defaults(entries):
    """Строит словарь значений по умолчанию из шаблона (рекурсивно по разделам)."""
    result = {}
    for entry in entries:
        if entry[0] == "leaf":
            _, key, default, _comment = entry
            result[key] = default
        else:
            _, key, _comment, children = entry
            result[key] = _defaults(children)  # раздел - вложенный словарь
    return result


def default_settings():
    """Возвращает новый словарь настроек со всеми значениями по умолчанию."""
    return _defaults(TEMPLATE)


def _merge(defaults, user):
    """Накладывает значения пользователя на значения по умолчанию.

    Правила:
      * ключи, которых нет у пользователя, остаются по умолчанию (так старый файл
        продолжает работать после добавления в программу новых полей);
      * ключи пользователя, которых нет в шаблоне, отбрасываются;
      * если раздел у пользователя испорчен (вместо вложенных полей - не словарь),
        берём раздел по умолчанию, чтобы программа не упала.
    """
    merged = {}
    for key, default_value in defaults.items():
        if key in user:
            user_value = user[key]
            if isinstance(default_value, dict):
                # Раздел: сливаем рекурсивно, но только если у пользователя тоже словарь.
                merged[key] = _merge(default_value, user_value) if isinstance(user_value, dict) \
                    else default_value
            else:
                merged[key] = user_value
        else:
            merged[key] = default_value
    return merged


