def parse_jsonc(text):
    """Превращает текст .jsonc (JSON со строками-комментариями) в обычные данные Python.

    Как это работает: строки, которые (после пробелов) начинаются с "//",
    заменяются на ПУСТЫЕ строки, затем остаток разбирается обычным json.loads.
    Почему заменяем на пустые, а не удаляем: тогда номера строк остаются теми же, и
    сообщение об ошибке ("строка 27") указывает на нужное место в файле.

    Ограничение: комментарии - только на отдельных строках. Искать "//" внутри
    строки нельзя: он встречается в обычных данных (например, в адресах https://).
    """
    lines = text.splitlines()
    cleaned = ["" if line.lstrip().startswith("//") else line for line in lines]
    try:
        return json.loads("\n".join(cleaned))
    except json.JSONDecodeError as e:
        raise SettingsError(f"ошибка в файле настроек: строка {e.lineno}, {e.msg}") from e


def load_settings(path):
    """Читает файл настроек и возвращает полный словарь (с недостающими полями по умолчанию)."""
    text = Path(path).read_text(encoding="utf-8")
    user = parse_jsonc(text)
    if not isinstance(user, dict):
        raise SettingsError("файл настроек должен содержать объект { ... } на верхнем уровне")
    return _merge(default_settings(), user)


def settings_problems(settings):
    """Проверяет значения настроек. Возвращает список описаний проблем (пустой = всё в порядке).

    Как и validate_card в schema.py, возвращает список, а не бросает ошибку: так
    можно показать пользователю сразу все проблемы.
    """
    problems = []

    if settings["settings_version"] != SETTINGS_VERSION:
        problems.append(
            f"settings_version = {settings['settings_version']}, "
            f"а программа понимает версию {SETTINGS_VERSION}")

    for key in ("model", "export_method", "profile_id"):
        value = settings["source"][key]
        if not isinstance(value, str) or not value:
            problems.append(f"source.{key} должно быть непустым текстом")

    limit = settings["limits"]["bundle_max_chars"]
    # bool - подвид int в Python (True == 1), поэтому отдельно исключаем его.
    if isinstance(limit, bool) or not isinstance(limit, int) or limit <= 0:
        problems.append("limits.bundle_max_chars должно быть целым числом больше нуля")

    if not isinstance(settings["automation"]["enabled"], bool):
        problems.append("automation.enabled должно быть true или false")

    s2 = settings["stage2"]
    if not isinstance(s2["use_lemmas"], bool):
        problems.append("stage2.use_lemmas должно быть true или false")
    for key in ("prompt_weight", "keywords_shown", "sentence_window"):
        value = s2[key]
        if isinstance(value, bool) or not isinstance(value, int) or value < 1:
            problems.append(f"stage2.{key} должно быть целым числом не меньше 1")

    return problems


