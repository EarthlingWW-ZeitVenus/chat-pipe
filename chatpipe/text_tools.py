# "Служебный файл", который Gemini добавляет в ответы, для нас шум. Адаптер вырезает
# его из ответа, а на его месте оставляет метку-заменитель:
#     [[СЛУЖЕБНЫЙ ТЕКСТ ВЫРЕЗАН: svc-<id карточки>]]
# Сам вырезанный текст пишется в отдельный файл (см. stage1_report.write_service_texts)
# под такой же меткой. Так можно проверить, что алгоритм счёл служебным, и при ошибке
# вернуть текст на место.

MARK_TEMPLATE = "[[СЛУЖЕБНЫЙ ТЕКСТ ВЫРЕЗАН: {marker}]]"
MARK_RE = re.compile(r"\[\[СЛУЖЕБНЫЙ ТЕКСТ ВЫРЕЗАН: (svc-[^\]\s]+)\]\]")


def marker_for(card_id):
    """Номер метки для карточки: svc-<id>."""
    return f"svc-{card_id}"


def placeholder_for(card_id):
    """Текст метки-заменителя, который вставляется в ответ на место вырезанного блока."""
    return MARK_TEMPLATE.format(marker=marker_for(card_id))
