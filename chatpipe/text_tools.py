# -*- coding: utf-8 -*-
"""
text_tools.py - общие текстовые инструменты, НЕ зависящие от конкретного чата.

Что здесь есть:
  sha(text)         короткий "отпечаток" текста (используется для идентификаторов)
  html_to_md(html)  превращает кусок HTML в Markdown
  plain_text(html)  превращает кусок HTML в чистый текст, сохраняя переносы строк

Почему это отдельный модуль: HTML встречается в разных экспортах, а не только в
Google Takeout, и каждый адаптер может пользоваться этими функциями. Сам модуль
ничего не знает ни об адаптерах, ни о карточках.
"""

# ==============================================================================
# ПОДКЛЮЧЕНИЕ МОДУЛЕЙ
# ==============================================================================

import hashlib    # хэш-функции. Хэш превращает любой текст в короткий "отпечаток"
                  # фиксированной длины: одинаковый текст -> одинаковый отпечаток
import html       # нам нужна html.unescape: превращает "&amp;" -> "&", "&#39;" -> "'"
import re         # регулярные выражения: язык шаблонов для поиска и замены текста
from html.parser import HTMLParser  # заготовка для разбора HTML (см. класс _Md)


# ==============================================================================
# ОТПЕЧАТОК ТЕКСТА
# ==============================================================================

def sha(text, n=16):
    """Короткий "отпечаток" (хэш) текста: первые n символов SHA-1.

    Одинаковый текст всегда даёт одинаковый отпечаток, а разный - почти наверняка
    разный. Мы используем его как идентификатор карточки.
    .encode("utf-8") превращает текст в байты (хэш считается от байтов);
    .hexdigest() даёт результат в виде строки из 40 шестнадцатеричных символов;
    [:n] берёт первые n.
    """
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:n]


# ==============================================================================
# HTML -> MARKDOWN (небольшой конвертер на html.parser)
# ==============================================================================
# Ответы в экспортах нередко лежат как HTML (<p>, <h3>, <ul>, <pre> ...). Для
# работы с языковыми моделями удобнее Markdown. Конвертер читает HTML по порядку
# и выдаёт Markdown.
#
# КАК РАБОТАЕТ HTMLParser. Это "событийный" разбор: мы отдаём ему HTML, а он
# сам идёт по тексту и при каждой находке вызывает наши методы:
#   handle_starttag - встретился открывающий тег, например <p>
#   handle_endtag   - встретился закрывающий тег, например </p>
#   handle_data     - встретился обычный текст между тегами
# Мы создаём СВОЙ класс на основе HTMLParser (запись class _Md(HTMLParser)) и
# переопределяем эти методы: в них пишем, что делать с каждым тегом.
# Имя класса начинается с "_" - договорённость "это внутреннее устройство
# файла, снаружи им напрямую не пользуются" (снаружи есть функция html_to_md).

class _Md(HTMLParser):

    def __init__(self):
        # __init__ - "конструктор": вызывается один раз при создании объекта и
        # задаёт начальное состояние. "self" - сам создаваемый объект; всё, что
        # записано как self.что_то, принадлежит этому объекту и живёт, пока он жив.
        #
        # super().__init__(...) запускает конструктор родительского класса
        # HTMLParser. convert_charrefs=True просит его сразу превращать
        # "&amp;" -> "&" в тексте (так нам не нужно делать это самим).
        super().__init__(convert_charrefs=True)

        self.parts = []   # сюда складываем кусочки результата; в конце склеим в один текст
        self.codes = []   # блоки кода (<pre>) храним отдельно - объяснение в handle_endtag
        self.lists = []   # стек вложенных списков; элемент: [тип "ul"/"ol", счётчик пунктов]
        self.hrefs = []   # стек адресов ссылок (для <a href="...">)
        self.pre = 0      # глубина вложенности внутри <pre> (0 = мы не внутри блока кода)
        self.skip = 0     # глубина внутри <script>/<style> (их содержимое выбрасываем)
        self._pre_idx = 0 # позиция в self.parts, где начался текущий блок <pre>
        self._last = ""   # последний выданный символ (нужен, чтобы не ставить лишние пробелы)

    def _emit(self, s):
        """Добавляет кусок текста s в результат и запоминает его последний символ."""
        if s:  # пустые строки не добавляем (пустая строка в условии = "ложь")
            self.parts.append(s)
            self._last = s[-1]  # s[-1] - последний символ строки

    def _block(self):
        """Вставляет пустую строку (разрыв абзаца), если результат уже не пуст.

        Зачем "if self.parts": в самом начале документа разрыв не нужен.
        """
        if self.parts:
            self._emit("\n\n")  # "\n" - символ перевода строки; два подряд = пустая строка

    def handle_starttag(self, tag, attrs):
        """Вызывается на каждый ОТКРЫВАЮЩИЙ тег. tag - имя ("p"), attrs - его атрибуты."""

        # <script> и <style> - не контент страницы. Включаем режим "пропуск":
        # пока skip > 0, весь текст и теги игнорируются.
        if tag in ("script", "style"):
            self.skip += 1
            return  # return без значения = "выйти из функции прямо здесь"
        if self.skip:
            return

        # Внутри блока кода (<pre>) теги нам не интересны - берём только текст как
        # есть, с сохранением пробелов и переносов строк. Поэтому сразу выходим.
        if self.pre:
            return

        # Заголовки h1..h6 -> "#", "##", ... Номер уровня берём из имени тега:
        # tag[1] - вторая буква ("3" из "h3"), int() делает из неё число,
        # "#" * 3 даёт "###". Перед заголовком нужен разрыв абзаца.
        if tag in ("h1", "h2", "h3", "h4", "h5", "h6"):
            self._block()
            self._emit("#" * int(tag[1]) + " ")

        # Блочные теги просто начинают новый абзац.
        elif tag in ("p", "div", "section", "article", "table"):
            self._block()

        # Цитата: в Markdown строка цитаты начинается с "> ".
        elif tag == "blockquote":
            self._block()
            self._emit("> ")

        # <br> - перенос строки внутри абзаца.
        elif tag == "br":
            self._emit("\n")

        # <hr> - горизонтальная линия; в Markdown это "---" отдельной строкой.
        elif tag == "hr":
            self._block()
            self._emit("---")
            self._block()

        # Начало списка. Кладём в стек запись [тип, счётчик]. Стек нужен потому,
        # что списки бывают вложенными: у каждого уровня свой счётчик пунктов.
        # Разрыв абзаца перед списком ставим только у самого внешнего списка.
        elif tag in ("ul", "ol"):
            if not self.lists:
                self._block()
            self.lists.append([tag, 0])

        # Пункт списка. Отступ = 2 пробела на каждый уровень вложенности.
        # max(..., 0) страхует от отрицательного числа, если <li> встретился
        # вне списка. Маркер: "1. " для нумерованного списка (счётчик растёт),
        # "- " для маркированного.
        elif tag == "li":
            depth = max(len(self.lists) - 1, 0)
            self._emit("\n" + "  " * depth)
            if self.lists and self.lists[-1][0] == "ol":
                self.lists[-1][1] += 1
                self._emit(f"{self.lists[-1][1]}. ")
            else:
                self._emit("- ")

        # Жирный, курсив, строчный код: открывающая и закрывающая метки в
        # Markdown одинаковы (**, *, `), поэтому тут пишем метку, а в
        # handle_endtag - такую же.
        elif tag in ("strong", "b"):
            self._emit("**")
        elif tag in ("em", "i"):
            self._emit("*")
        elif tag == "code":
            self._emit("`")

        # Начало блока кода. Увеличиваем глубину и запоминаем, с какой позиции в
        # self.parts начинается код (len(self.parts) - сколько кусочков уже есть).
        elif tag == "pre":
            self.pre += 1
            self._pre_idx = len(self.parts)

        # Ссылка: запоминаем адрес (dict(attrs) превращает список пар атрибутов в
        # словарь; .get("href") достаёт адрес или None; "or ''" заменяет None на
        # пустую строку). Текст ссылки пойдёт в [скобках], а адрес допишем на
        # закрывающем теге.
        elif tag == "a":
            self.hrefs.append(dict(attrs).get("href") or "")
            self._emit("[")

        # Строка таблицы: просто новая строка.
        elif tag == "tr":
            self._emit("\n")

        # Картинки в архив не попадают, оставляем метку-заглушку.
        elif tag == "img":
            self._emit("[image]")

    def handle_endtag(self, tag):
        """Вызывается на каждый ЗАКРЫВАЮЩИЙ тег."""

        # Конец <script>/<style>: уменьшаем глубину пропуска. max(..., 0) не даёт
        # ей уйти ниже нуля при кривой разметке.
        if tag in ("script", "style"):
            self.skip = max(self.skip - 1, 0)
            return
        if self.skip:
            return

        # Конец блока кода - самая хитрая часть.
        if tag == "pre":
            if self.pre:
                self.pre -= 1
                if self.pre == 0:  # вышли из самого внешнего <pre>
                    # Забираем все кусочки, добавленные с начала блока, склеиваем
                    # в один текст и удаляем их из self.parts (del).
                    code = "".join(self.parts[self._pre_idx:])
                    del self.parts[self._pre_idx:]

                    # Код кладём в отдельный список self.codes, а в основной текст
                    # вставляем МЕТКУ-ЗАМЕНИТЕЛЬ вида "\x00C0\x00" (символ \x00 в
                    # обычном тексте не встречается, поэтому метка не спутается с
                    # настоящим содержимым). Зачем: в конце мы делаем "уборку"
                    # пробелов по всему тексту, а в коде пробелы и переносы
                    # трогать нельзя. Код хранится в стороне и возвращается на
                    # место уже ПОСЛЕ уборки (см. метод result).
                    # .strip("\n") убирает лишние переводы строк по краям кода.
                    self.codes.append(code.strip("\n"))
                    self._block()
                    self._emit(f"\x00C{len(self.codes) - 1}\x00")
                    self._block()
            return

        if self.pre:
            return

        # Закрылся блочный элемент - завершаем абзац.
        if tag in ("h1", "h2", "h3", "h4", "h5", "h6", "p", "div", "section",
                   "article", "blockquote", "table"):
            self._block()

        # Закрылся список: снимаем его со стека (pop). Разрыв абзаца - только
        # когда закрылся самый внешний список (стек опустел).
        elif tag in ("ul", "ol"):
            if self.lists:
                self.lists.pop()
            if not self.lists:
                self._block()

        elif tag in ("strong", "b"):
            self._emit("**")
        elif tag in ("em", "i"):
            self._emit("*")
        elif tag == "code":
            self._emit("`")

        # Закрылась ссылка: достаём запомненный адрес и пишем "](адрес)".
        # Получается Markdown-ссылка [текст](адрес).
        elif tag == "a":
            href = self.hrefs.pop() if self.hrefs else ""
            self._emit(f"]({href})" if href else "]")

        # Конец ячейки таблицы: разделитель " | ".
        elif tag in ("td", "th"):
            self._emit(" | ")

    def handle_data(self, data):
        """Вызывается на обычный ТЕКСТ между тегами (data - сам текст)."""
        if self.skip:
            return

        # В коде текст сохраняем в точности как есть.
        if self.pre:
            self._emit(data)
            return

        # Вне кода делаем то же, что браузер: любая серия пробелов, табов и
        # переносов строк сворачивается в ОДИН пробел. (В HTML переносы строк в
        # исходнике - это просто пробелы; видимые переносы дают теги <br>, <p>.)
        # \s+ - "один или больше пробельных символов" (включая неразрывный пробел).
        d = re.sub(r"\s+", " ", data)

        # Не ставим пробел в начале строки и второй пробел подряд.
        # lstrip(" ") убирает пробелы слева.
        if self._last in ("", "\n", " "):
            d = d.lstrip(" ")
        self._emit(d)

    def result(self):
        """Завершает разбор и возвращает готовый Markdown-текст."""
        self.close()  # сообщаем парсеру, что текст закончился (он дорабатывает хвост)
        text = "".join(self.parts)  # склеиваем все кусочки в одну строку

        # Уборка 1: убираем пробелы и табы перед переводом строки.
        # [ \t]+\n - "один или больше пробелов/табов, затем перевод строки".
        text = re.sub(r"[ \t]+\n", "\n", text)

        # Уборка 2: три и больше переводов строки подряд -> два (одна пустая строка).
        # .strip() - убираем пустоты в начале и конце.
        text = re.sub(r"\n{3,}", "\n\n", text).strip()

        def put_code(m):
            """Подставляет блок кода вместо метки "\x00C<номер>\x00"."""
            code = self.codes[int(m.group(1))]  # group(1) - номер из метки

            # Проблема: внутри кода сам может быть Markdown-код с тройными
            # обратными кавычками (так бывает, когда ИИ показывает пример
            # форматирования). Если обернуть такой код в обычные ```, внутренние
            # ``` досрочно закроют блок. Правило Markdown: ограждение (fence)
            # должно быть длиннее любой серии кавычек внутри.
            # re.findall(r"`+", code) находит все серии кавычек; берём самую
            # длинную. "or [0]" - запасной вариант, если серий нет вообще.
            longest = max([len(r) for r in re.findall(r"`+", code)] or [0])
            fence = "`" * max(3, longest + 1)  # минимум 3, иначе на одну больше самой длинной серии
            return f"{fence}\n{code}\n{fence}"

        # re.sub(шаблон, функция, текст): для каждой найденной метки вызывает
        # функцию и подставляет то, что она вернёт. (\d+ - одна или больше цифр.)
        return re.sub(r"\x00C(\d+)\x00", put_code, text)


def html_to_md(fragment):
    """Превращает кусок HTML в Markdown. Никогда не падает на кривой разметке."""
    p = _Md()  # создаём новый конвертер (отдельный на каждый фрагмент: у него своё состояние)
    try:
        p.feed(fragment)  # отдаём HTML парсеру: он вызывает наши handle_* методы
        return p.result()
    except Exception:
        # Запасной путь: если разбор сломался, просто вырезаем все теги и
        # возвращаем голый текст. Лучше грубый текст, чем остановка всей
        # программы на одной плохой карточке из трёх тысяч.
        return html.unescape(re.sub(r"<[^>]+>", " ", fragment)).strip()


def plain_text(fragment):
    """Для ЗАПРОСА пользователя: <br> -> перенос строки, теги убираем, переносы сохраняем.

    Почему не html_to_md: в запросах переносы строк - настоящие (там часто лежат
    вставленные логи и конфиги), а html_to_md схлопнул бы их в пробелы.
    """
    s = re.sub(r"<br\s*/?>", "\n", fragment)  # <br>, <br/> и <br /> -> перенос строки
    s = re.sub(r"<[^>]+>", "", s)             # любой тег (<...>) удаляем
    s = html.unescape(s).replace("\xa0", " ") # "&amp;" -> "&"; неразрывный пробел -> обычный
    return s.strip()


# ==============================================================================
# БЛОКИ КОДА В MARKDOWN: ОДНО МЕСТО, КОТОРОЕ ЗНАЕТ, ГДЕ КОД, А ГДЕ ТЕКСТ
# ==============================================================================
# Ответ ИИ (answer_md) - это Markdown, в котором код ограждён тройными обратными
# кавычками:
#
#     Вот пример:
#     ```bash
#     docker compose up -d
#     ```
#
# Многим частям программы нужно различать "обычный текст" и "код":
#   * подсчёт ключевых слов должен ПРОПУСКАТЬ код (имена переменных и логи только
#     портят статистику);
#   * выборка предложений не должна резать код на куски;
#   * сборка XML для ИИ кладёт код в отдельный тег.
# Чтобы каждая часть не придумывала свой способ, это умеет ровно ОДНА функция -
# split_blocks. Остальные просто вызывают её. Так скрипты никогда "не лезут внутрь"
# кода: они видят его как цельный блок.

# Регулярное выражение для блока кода, по частям:
#   ^                    начало строки (флаг re.M делает ^ началом КАЖДОЙ строки)
#   (?P<fence>`{3,})     "ограждение": три и больше обратных кавычек; (?P<имя>...)
#                        даёт группе имя, чтобы потом сослаться на неё
#   (?P<info>[^`\n]*)    остаток первой строки - обычно язык ("bash"); без кавычек
#   \n                   конец первой строки
#   (?P<code>.*?)        сам код (лениво: до ПЕРВОГО подходящего закрытия)
#   ^(?P=fence)`*[ \t]*$ закрывающая строка: то же ограждение (?P=fence) (допускаем
#                        лишние кавычки в конце) и пробелы до конца строки
# Закрывающая серия должна совпадать с открывающей, поэтому код, внутри которого
# есть собственные ```, оберну более длинным ограждением (см. html_to_md) - и
# внутренние короткие серии не закроют блок досрочно.
_FENCE_RE = re.compile(
    r"^(?P<fence>`{3,})(?P<info>[^`\n]*)\n(?P<code>.*?)^(?P=fence)`*[ \t]*$",
    re.S | re.M)


def split_blocks(md):
    """Делит Markdown на куски "текст" и "код".

    Вход:  md - текст в формате Markdown.
    Выход: список кортежей (вид, содержимое, язык):
             ("text", "обычный текст...", "")
             ("code", "docker compose up -d", "bash")
           Пустые куски текста в список не попадают. Если склеить все куски по
           порядку, получится исходное содержание (без самих ограждений).
    """
    blocks = []
    position = 0  # откуда продолжать копировать текст
    # finditer отдаёт по очереди все найденные блоки кода.
    for m in _FENCE_RE.finditer(md):
        before = md[position:m.start()]  # текст между прошлым блоком и этим
        if before.strip():
            blocks.append(("text", before.strip("\n"), ""))
        code = m.group("code")
        if code.endswith("\n"):
            code = code[:-1]  # последний перевод строки перед закрытием - не часть кода
        blocks.append(("code", code, m.group("info").strip()))
        position = m.end()
    tail = md[position:]  # текст после последнего блока кода
    if tail.strip():
        blocks.append(("text", tail.strip("\n"), ""))
    return blocks


def strip_code(md):
    """Возвращает Markdown БЕЗ блоков кода (только текстовые куски, через пустую строку).

    Нужна для анализа слов: код в статистике не участвует.
    """
    return "\n\n".join(text for kind, text, _lang in split_blocks(md) if kind == "text")


